"""Employer documents for the principal officer portal (FR-PRT-001), A4 PDF with the
fund letterhead of the receipt documents:

- **Statement of contributions** for a period: month by month what the schedules
  said, what was credited to members and the money received; then each member's
  credited totals (employee / employer / AVC / severance).
- **Contribution invoice** for a month: each member's expected contributions (salary on
  record × category rates), employer-paid fees on that total (fee rules in force at
  month end), the due date and where to pay. A statement of the amount due, not a tax
  invoice.
- **Arrears statement**: expected vs paid per month from `arrears.scheme_arrears`, days
  overdue, ageing and late-payment interest (calculated, not posted).
"""

ZERO = Decimal("0.00")
CELL = ParagraphStyle("c", parent=BODY, fontSize=8.5, leading=11)
CELL_R = ParagraphStyle("cr", parent=CELL, alignment=2)
HEAD = ParagraphStyle("h", parent=CELL, textColor=colors.white, fontName="Helvetica-Bold")
HEAD_R = ParagraphStyle("hr", parent=HEAD, alignment=2)
SECTION = ParagraphStyle("sec", parent=BODY, fontSize=11.5, fontName="Helvetica-Bold", spaceBefore=12, spaceAfter=4)


def _amt(d: Decimal | None) -> str:
    return f"{d:,.2f}" if d is not None else "—"


def _letterhead(fund: Fund, scheme: Scheme, title: str, subtitle: str) -> list:
    address = ", ".join(a for a in (fund.address_line1, fund.address_line2, fund.address_line3, fund.address_line4, fund.address_line5) if a)
    contact = " · ".join(x for x in (address, fund.phone, fund.email, f"TPIN {fund.tpin}" if fund.tpin else None) if x)
    return [Paragraph(fund.name, FUND_NAME), Paragraph(contact or fund.code, SMALL), Paragraph(title, TITLE),
            Paragraph(f"{scheme.code} — {scheme.name} · {subtitle}", BODY), Spacer(1, 8)]


def _grid(header: list[str], rows: list[list[str]], widths: list[float], right: set[int], total: list[str] | None = None) -> Table:
    data = [[Paragraph(h, HEAD_R if i in right else HEAD) for i, h in enumerate(header)]]
    for r in rows:
        data.append([Paragraph(str(v), CELL_R if i in right else CELL) for i, v in enumerate(r)])
    if total:
        data.append([Paragraph(f"<b>{v}</b>", CELL_R if i in right else CELL) for i, v in enumerate(total)])
    table = Table(data, colWidths=[WIDTH * w for w in widths], repeatRows=1)
    style = [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(settings.brand_color)), ("VALIGN", (0, 0), (-1, -1), "TOP"),
             ("LINEBELOW", (0, 1), (-1, -1), 0.25, colors.HexColor("#d5dadd")), ("TOPPADDING", (0, 0), (-1, -1), 3),
             ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
             ("LEFTPADDING", (0, 0), (-1, -1), 3), ("RIGHTPADDING", (0, 0), (-1, -1), 3)]
    if total:
        style.append(("LINEABOVE", (0, -1), (-1, -1), 0.8, colors.black))
    table.setStyle(TableStyle(style))
    return table


def _footer(fund: Fund, printed: date) -> list:
    return [Spacer(1, 14), Paragraph(f"Computer-generated by {settings.brand_name} on behalf of {fund.name}; no signature is required. "
                                     f"Printed {printed:%d %B %Y}.", SMALL)]


def _build(story: list, title: str) -> bytes:
    out = io.BytesIO()
    SimpleDocTemplate(out, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=18 * mm, bottomMargin=18 * mm,
                      title=title, author=settings.brand_name).build(story)
    return out.getvalue()


# ---- statement of contributions


@dataclass
class MonthLine:
    month: date
    references: list[str] = field(default_factory=list)
    on_schedules: Decimal = ZERO
    credited: Decimal = ZERO
    # Money applied to the month's credited schedules (contributions + fees the employer pays).
    paid: Decimal = ZERO
    waiting: Decimal = ZERO


def contribution_statement(db: Session, scheme: Scheme, first: date, last: date, printed: date) -> bytes:
    fund = db.get(Fund, scheme.fund_id)
    first, last = periods.month_start(first), periods.month_start(last)
    months: dict[date, MonthLine] = {}
    per_member: dict = defaultdict(lambda: defaultdict(lambda: ZERO))
    scheds = db.execute(select(ContributionSchedule).where(
        ContributionSchedule.scheme_id == scheme.id, ContributionSchedule.contribution_month.between(first, last),
        ContributionSchedule.status.in_((ScheduleStatus.ready, ScheduleStatus.allocated)),
    ).order_by(ContributionSchedule.contribution_month, ContributionSchedule.reference)).scalars().all()
    for s in scheds:
        m = months.setdefault(s.contribution_month, MonthLine(s.contribution_month))
        m.references.append(s.reference)
        m.on_schedules += s.total
        if s.status == ScheduleStatus.allocated:
            m.credited += s.total
            allocation = db.execute(select(ContributionAllocation).where(
                ContributionAllocation.schedule_id == s.id, ContributionAllocation.status == AllocationStatus.posted)).scalar_one_or_none()
            m.paid += allocation.amount if allocation else s.total
            for line in db.execute(select(ContributionScheduleLine).where(ContributionScheduleLine.schedule_id == s.id)).scalars():
                for key in schedules.AMOUNTS:
                    per_member[line.member_id][key] += getattr(line, key)
        else:
            m.waiting += s.total

    rows = sorted(months.values(), key=lambda m: m.month)
    story = _letterhead(fund, scheme, "Statement of contributions", f"{periods.label(first)} to {periods.label(last)}")
    if not rows:
        story.append(Paragraph("No contribution schedules were sent for this period.", BODY))
    else:
        story.append(_grid(
            ["Month", "Schedules", "On schedules", "Credited to members", "Paid (incl. fees)"],
            [[periods.label(m.month), ", ".join(m.references) or "—", _amt(m.on_schedules), _amt(m.credited), _amt(m.paid)] for m in rows],
            [0.13, 0.33, 0.18, 0.18, 0.18], {2, 3, 4},
            ["Total", "", _amt(sum((m.on_schedules for m in rows), ZERO)), _amt(sum((m.credited for m in rows), ZERO)),
             _amt(sum((m.paid for m in rows), ZERO))],
        ))
        waiting = sum((m.waiting for m in rows), ZERO)
        if waiting:
            story.append(Paragraph(f"{_money(waiting)} is on schedules sent but not yet credited to members.", SMALL))
    if per_member:
        names = {m.id: m for m in db.execute(select(Member).where(Member.id.in_([k for k in per_member if k]))).scalars()}
        member_rows = sorted(((names[k], v) for k, v in per_member.items() if k in names), key=lambda p: (p[0].last_name, p[0].first_name))
        story += [Paragraph("Credited per member", SECTION), _grid(
            ["Member", "Employee", "Employer", "AVC", "Severance", "Total"],
            [[f"{m.account_code} {m.full_name}", _amt(v["employee"]), _amt(v["employer"]), _amt(v["voluntary"]), _amt(v["severance"]),
              _amt(sum(v.values(), ZERO))] for m, v in member_rows],
            [0.34, 0.13, 0.13, 0.13, 0.13, 0.14], {1, 2, 3, 4, 5},
        )]
    story += _footer(fund, printed)
    return _build(story, f"Statement of contributions {scheme.code}")


# ---- invoice (amount due) for a month


def _collection_account(db: Session, fund: Fund) -> tuple[FundBankAccount, Bank] | None:
    row = db.execute(select(FundBankAccount, Bank).join(Bank, Bank.id == FundBankAccount.bank_id).where(
        FundBankAccount.fund_id == fund.id, FundBankAccount.active.is_(True),
        FundBankAccount.purpose.in_((BankAccountPurpose.collections, BankAccountPurpose.general)),
    ).order_by(FundBankAccount.purpose, FundBankAccount.sort_order)).first()
    return (row[0], row[1]) if row else None


def invoice(db: Session, scheme: Scheme, month: date, printed: date) -> bytes:
    fund = db.get(Fund, scheme.fund_id)
    month = periods.month_start(month)
    lines, missing = [], []
    for m in schedules.expected_members(db, scheme, month):
        e = schedules.expected_for(db, m, month)
        if e.employee is None and e.employer is None:
            missing.append(m)
            continue
        lines.append((m, e))
    contributions = sum(((e.employee or ZERO) + (e.employer or ZERO) for _, e in lines), ZERO)
    fees = []
    for rule in fee_rules.rules_in_force(db, fund.id, scheme.id, schedules.month_end(month)):
        if rule.basis == FeeBasis.pct_contributions and rule.payer == FeePayer.employer:
            amount = ledger.money(contributions * rule.rate / 100)
            if amount:
                fees.append((rule, amount))
    total = contributions + sum((a for _, a in fees), ZERO)
    due = arrears.due_date(scheme, month)
    reference = f"{scheme.code}-{month:%Y%m}"
    account = _collection_account(db, fund)

    story = _letterhead(fund, scheme, "Contribution invoice", f"contributions for {periods.label(month)}")
    story += [_facts([
        ("Amount due", f"<b>{_money(total)}</b>"),
        ("Due by", f"{due:%d %B %Y}"),
        ("Pay into", f"{account[1].name} · {account[0].account_name} · account {account[0].account_number}" if account else
         "Ask us for the fund's bank account"),
        ("Payment reference", f"<b>{reference}</b>"),
    ]), Spacer(1, 6)]
    story.append(_grid(
        ["Member", "Pensionable salary", "Employee", "Employer", "Total"],
        [[f"{m.account_code} {m.full_name}", _amt(e.salary), _amt(e.employee), _amt(e.employer),
          _amt((e.employee or ZERO) + (e.employer or ZERO))] for m, e in lines],
        [0.36, 0.17, 0.15, 0.15, 0.17], {1, 2, 3, 4},
        ["Contributions", "", _amt(sum((e.employee or ZERO for _, e in lines), ZERO)), _amt(sum((e.employer or ZERO for _, e in lines), ZERO)),
         _amt(contributions)],
    ))
    if fees:
        story += [Spacer(1, 6), _grid(["Fee (paid by the employer)", "Rate", "Amount"],
                                      [[r.name, f"{r.rate.normalize():f}% of contributions", _amt(a)] for r, a in fees],
                                      [0.5, 0.3, 0.2], {2})]
    story += [Spacer(1, 6), _facts([("Total due", f"<b>{_money(total)}</b>")])]
    if missing:
        story += [Spacer(1, 6), Table([[Paragraph(
            f"<b>{len(missing)} member{'s have' if len(missing) != 1 else ' has'} no salary on record</b> and "
            f"{'are' if len(missing) != 1 else 'is'} not included: " + ", ".join(f"{m.account_code} {m.full_name}" for m in missing[:12]) +
            ". Add their salaries and include them on the schedule.", BANNER)]], colWidths=[WIDTH],
            style=TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fdf3e1")), ("TOPPADDING", (0, 0), (-1, -1), 6),
                              ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))]
    story += [Spacer(1, 8), Paragraph(
        "Worked out from each member's salary on record and the category's contribution rates. Voluntary contributions (AVC) and "
        "severance are added on the schedule. Send the schedule with the payment so members can be credited. "
        "This is a statement of the amount due, not a tax invoice.", SMALL)]
    story += _footer(fund, printed)
    return _build(story, f"Contribution invoice {reference}")


# ---- arrears


def arrears_statement(db: Session, scheme: Scheme, as_at: date) -> bytes:
    fund = db.get(Fund, scheme.fund_id)
    result = arrears.scheme_arrears(db, scheme, as_at)
    overdue = [m for m in result.months if m.arrears > 0 and m.days_overdue > 0]
    upcoming = [m for m in result.months if m.arrears > 0 and m.days_overdue == 0]
    story = _letterhead(fund, scheme, "Arrears statement", f"as at {as_at:%d %B %Y}")
    story += [_facts([
        ("Overdue contributions", f"<b>{_money(result.total_arrears)}</b>"),
        ("Months overdue", str(len(overdue))),
        ("Late-payment interest", _money(result.total_interest) if result.total_interest is not None else "No interest rate set"),
    ]), Spacer(1, 6)]
    if not overdue:
        story.append(Paragraph("Nothing is overdue.", BODY))
    else:
        story.append(_grid(
            ["Month", "Due by", "Expected", "Paid", "Owing", "Days overdue", "Interest"],
            [[periods.label(m.month), f"{m.due_date:%d %b %Y}", _amt(m.expected), _amt(m.paid), _amt(m.arrears), str(m.days_overdue),
              _amt(m.interest)] for m in overdue],
            [0.13, 0.14, 0.15, 0.14, 0.15, 0.13, 0.16], {2, 3, 4, 5, 6},
            ["Total", "", "", "", _amt(result.total_arrears), "", _amt(result.total_interest)],
        ))
    for m in upcoming:
        story.append(Paragraph(f"Not due yet: {periods.label(m.month)} — {_money(m.arrears)} still to pay by {m.due_date:%d %B %Y}.", SMALL))
        buckets: dict[str, Decimal] = defaultdict(lambda: ZERO)
        for m in overdue:
            buckets[m.bucket] += m.arrears
        if buckets:
            story += [Paragraph("Age of the overdue amount", SECTION),
                      _grid(["Overdue for", "Amount"], [[k, _amt(v)] for k, v in buckets.items()], [0.6, 0.4], {1})]
    story += [Spacer(1, 8), Paragraph(
        "Expected = members' salaries on record × the category rates; paid = schedules credited to members. A month is due by the "
        "employer's contribution day of the following month. Interest is calculated at the rate in force on the due date and is "
        "not yet charged.", SMALL)]
    story += _footer(fund, as_at)
    return _build(story, f"Arrears statement {scheme.code}")
